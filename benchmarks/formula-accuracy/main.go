// ─── Types ──────────────────────────────────────────────────────────

var ROUTER = router.DeployedRouter
var DUMMY_SENDER = common.HexToAddress("0x000000000000000000000000000000000000dEaD")

// tokenAmounts maps token address → amount of that token worth ~0.1 AVAX (~$1).
// Loaded from formulas/data/token_amounts.txt (generated by tools/token-pricer).
var tokenAmounts = formulas.LoadEmbeddedTokenAmounts()

// poolAmountKey identifies a (pool, direction) for amount lookups.
type poolAmountKey struct {
	pool common.Address
	dir  int // 0 = token0→token1, 1 = token1→token0
}

type quoteKey struct {
	pool    common.Address
	dirIn   int // input token index
	dirOut  int // output token index
}

type typeStats struct {
	Quotes    int     // total quotes (2 per pool)
	HotMs     float64 // hot pass execution time
	Match     int     // formula == EVM (within tolerance)
	Overquote int     // formula > EVM — CRITICAL, never acceptable
	Underquote int    // formula < EVM — safe, missed opportunity
	NonZero   int     // EVM ground truth was non-zero
	Formula   int     // quotes handled by formula
}

type blockResult struct {
	blockNum     uint64
	byType       map[int]*typeStats
	mismatchSet  map[quoteKey]bool // true = mismatched on this block
	overquoteSet map[quoteKey]bool // true = overquoted on this block
	mismatchLog  []string
}

var typeNames = map[int]string{
	0: "uniswap_v3", 1: "algebra", 2: "lfj_v1", 3: "lfj_v2",
	4: "dodo", 5: "woofi_v2", 6: "balancer_v3", 7: "pharaoh_v1",
	8: "v2", 9: "uniswap_v4", 10: "erc4626", 12: "wombat",
	13: "platypus", 16: "balancer_v2", 17: "cavalre", 18: "kyber_dmm",
	19: "synapse", 20: "trident",
}

// ─── Per-block benchmark ────────────────────────────────────────────

func runBlockBenchmark(
	blockNum uint64,
	registry *formulas.Registry,
	pools []pathfinder.Pool,
	overrides []pathfinder.ParsedOverride,
	skipFormulas bool,
	stateServerHost string,
	useCache bool,
) (*blockResult, error) {
	stateServerURL := fmt.Sprintf("%s/debug/%d", strings.TrimRight(stateServerHost, "/"), blockNum)

	ls, err := statedb.Connect(stateServerURL)
	if err != nil {
		return nil, fmt.Errorf("block %d: %w", blockNum, err)
	}
	defer ls.Close()
	state := ls.State()
	cfg := ls.EVMConfig()

	// Register Balancer V3/V2 pools (EVM calls against this block's state)
	registerBalancerV3Pools(pools, state, cfg, registry)
	registerBalancerV2Pools(pools, state, cfg, registry)

	// Apply token overrides to this block's statedb
	baseWithOverrides := pathfinder.ApplyOverridesFlat(state, overrides)

	// Build PoolManager with this block's statedb
	poolReader := func(addr common.Address, key common.Hash) common.Hash {
		return state.GetState(addr, key)
	}
	pm := formulas.NewPoolManager(registry, poolReader)
	pm.SetBlockTimestamp(cfg.Timestamp)
	pm.SetEVMCaller(func(to common.Address, data []byte) ([]byte, bool) {
		result, _, err := statedb.ExecuteCall(state, cfg, DUMMY_SENDER, to, data)
		return result, err == nil
	})
	for i := range pools {
		if len(pools[i].Tokens) >= 2 {
			pm.SetPoolTokens(pools[i].Address, pools[i].Tokens...)
		}
		pm.SetPoolType(pools[i].Address, pools[i].PoolType, pools[i].Dex)
	}

	// ─── Pass 1: EVM ground truth (parallel, not timed) ───
	// EVMPool: N long-lived executors with persistent JUMPDEST cache.
	// Each executor has its own CallerContract — bytecodes scanned once, cached forever.
	// The pool channel limits concurrency to N (= NumCPU).
	evmCtx := statedb.GetCachedContext(cfg)
	evmPool := statedb.NewEVMPool(runtime.NumCPU(), evmCtx, baseWithOverrides)

	type groundEntry struct {
		key quoteKey
		out uint256.Int
	}
	var groundMu sync.Mutex
	evmGround := make(map[quoteKey]uint256.Int)

	// Resolve per-pool amounts from embedded token_amounts.txt.
	// Each direction uses the input token's amount (~0.1 AVAX worth).
	poolAmounts := make(map[poolAmountKey]*uint256.Int)
	skipped := 0
	for i := range pools {
		pool := &pools[i]
		if len(pool.Tokens) < 2 {
			continue
		}
		hasAny := false
		for ti, tok := range pool.Tokens {
			if amt, ok := tokenAmounts[tok]; ok {
				poolAmounts[poolAmountKey{pool.Address, ti}] = amt
				hasAny = true
			}
		}
		if !hasAny {
			skipped++
		}
	}
	if skipped > 0 {
		fmt.Fprintf(os.Stderr, "[benchmark] %d pools skipped (no token price, run tools/token-pricer)\n", skipped)
	}

	// Pass 1: EVM ground truth.
	// For each pool, find the direction with a known input amount (from tokenAmounts),
	// quote that direction, then use the EVM output as input for the reverse direction.
	// This ensures both directions use realistic amounts.
	fmt.Fprintf(os.Stderr, "[benchmark] pass 1 (EVM ground truth, %d workers)...", evmPool.Size())
	p1t0 := time.Now()

	// Phase 1a: forward direction (known amount → pool) in parallel
	type fwdWork struct {
		poolIdx  int
		fwdDir   int // input token index
		revDir   int // output token index
	}
	var fwdJobs []fwdWork
	for i := range pools {
		pool := &pools[i]
		if len(pool.Tokens) < 2 {
			continue
		}
		if len(pool.Tokens) == 2 {
			// 2-token pool: pick the direction where we have a token amount
			if poolAmounts[poolAmountKey{pool.Address, 0}] != nil {
				fwdJobs = append(fwdJobs, fwdWork{i, 0, 1})
			} else if poolAmounts[poolAmountKey{pool.Address, 1}] != nil {
				fwdJobs = append(fwdJobs, fwdWork{i, 1, 0})
			}
		} else {
			// N-token pool: create a job for each pair with a known input amount
			for ti := range pool.Tokens {
				if poolAmounts[poolAmountKey{pool.Address, ti}] == nil {
					continue
				}
				for tj := range pool.Tokens {
					if ti != tj {
						fwdJobs = append(fwdJobs, fwdWork{i, ti, tj})
					}
				}
			}
		}
	}

	var wg sync.WaitGroup
	for _, job := range fwdJobs {
		// Read amount under lock — goroutines from previous iterations may be writing poolAmounts
		groundMu.Lock()
		fwdAmt := poolAmounts[poolAmountKey{pools[job.poolIdx].Address, job.fwdDir}]
		groundMu.Unlock()
		wg.Add(1)
		go func(j fwdWork, amountIn *uint256.Int) {
			defer wg.Done()
			pool := &pools[j.poolIdx]
			tokenIn := pool.Tokens[j.fwdDir]
			tokenOut := pool.Tokens[j.revDir]
			calldata := pathfinder.EncodeSwapSingleWithExtra(pool.Address, pool.PoolType, tokenIn, tokenOut, amountIn, pool.ExtraData)

			ret, _, evmErr := evmPool.Execute(DUMMY_SENDER, ROUTER, calldata)
			if evmErr == nil && len(ret) >= 32 {
				var out uint256.Int
				out.SetBytes(ret[:32])
				groundMu.Lock()
				evmGround[quoteKey{pool.Address, j.fwdDir, j.revDir}] = out
				// For 2-token pools: set the reverse direction's amount to this EVM output
				if !out.IsZero() && len(pool.Tokens) == 2 {
					revAmt := new(uint256.Int).Set(&out)
					poolAmounts[poolAmountKey{pool.Address, j.revDir}] = revAmt
				}
				groundMu.Unlock()
			}
		}(job, fwdAmt)
	}
	wg.Wait()

	// Phase 1b: reverse direction (EVM forward output → pool) — only for 2-token pools
	var revJobs []fwdWork
	for _, job := range fwdJobs {
		pool := &pools[job.poolIdx]
		if len(pool.Tokens) != 2 {
			continue // multi-token pools already have all pairs from phase 1a
		}
		revDir := job.revDir
		if poolAmounts[poolAmountKey{pool.Address, revDir}] != nil {
			revJobs = append(revJobs, fwdWork{job.poolIdx, revDir, job.fwdDir})
		}
	}
	for _, job := range revJobs {
		wg.Add(1)
		go func(j fwdWork) {
			defer wg.Done()
			pool := &pools[j.poolIdx]
			tokenIn := pool.Tokens[j.fwdDir]
			tokenOut := pool.Tokens[j.revDir]
			amountIn := poolAmounts[poolAmountKey{pool.Address, j.fwdDir}]
			calldata := pathfinder.EncodeSwapSingleWithExtra(pool.Address, pool.PoolType, tokenIn, tokenOut, amountIn, pool.ExtraData)

			ret, _, evmErr := evmPool.Execute(DUMMY_SENDER, ROUTER, calldata)
			if evmErr == nil && len(ret) >= 32 {
				var out uint256.Int
				out.SetBytes(ret[:32])
				groundMu.Lock()
				evmGround[quoteKey{pool.Address, j.fwdDir, j.revDir}] = out
				groundMu.Unlock()
			}
		}(job)
	}
	wg.Wait()
	fmt.Fprintf(os.Stderr, " %dms\n", time.Since(p1t0).Milliseconds())

	// ─── Pass 2: Warm-up (not timed, serial) ───
	cs := statedb.NewCallState(baseWithOverrides) // for skipFormulas EVM path
	fmt.Fprintf(os.Stderr, "[benchmark] pass 2 (warm-up)...")
	p2t0 := time.Now()
	for i := range pools {
		pool := &pools[i]
		for ti := range pool.Tokens {
			for tj := range pool.Tokens {
				if ti == tj {
					continue
				}
				amountIn := poolAmounts[poolAmountKey{pool.Address, ti}]
				if amountIn == nil {
					continue
				}
				tokenIn := pool.Tokens[ti]
				tokenOut := pool.Tokens[tj]

				if !skipFormulas {
					if useCache {
						pm.Quote(pool.Address, amountIn, tokenIn, tokenOut)
					} else {
						pm.Get(pool.Address).Quote(amountIn, tokenIn, tokenOut)
					}
				} else {
					calldata := pathfinder.EncodeSwapSingleWithExtra(pool.Address, pool.PoolType, tokenIn, tokenOut, amountIn, pool.ExtraData)
					cs.Reset()
					evmCtx.ExecuteWithCallState(cs, DUMMY_SENDER, ROUTER, calldata)
				}
			}
		}
	}
	fmt.Fprintf(os.Stderr, " %dms\n", time.Since(p2t0).Milliseconds())

	// ─── Pass 3: Hot pass (timed + correctness) ───
	byType := make(map[int]*typeStats)
	getStats := func(poolType int) *typeStats {
		if s, ok := byType[poolType]; ok {
			return s
		}
		s := &typeStats{}
		byType[poolType] = s
		return s
	}

	fmt.Fprintf(os.Stderr, "[benchmark] pass 3 (hot pass)...\n")

	mismatchSet := make(map[quoteKey]bool)
	overquoteSet := make(map[quoteKey]bool)
	var mismatchLog []string
	t0 := time.Now()

	for i := range pools {
		pool := &pools[i]
		for ti := range pool.Tokens {
			for tj := range pool.Tokens {
				if ti == tj {
					continue
				}
			amountIn := poolAmounts[poolAmountKey{pool.Address, ti}]
			if amountIn == nil {
				continue // skipped pool (no hub token)
			}
			ts := getStats(pool.PoolType)
			ts.Quotes++
			tokenIn := pool.Tokens[ti]
			tokenOut := pool.Tokens[tj]

			key := quoteKey{pool.Address, ti, tj}
			evmResult := evmGround[key]
			if !evmResult.IsZero() {
				ts.NonZero++
			}

			var result uint256.Int
			if useCache {
				result = pm.Quote(pool.Address, amountIn, tokenIn, tokenOut)
			} else {
				result = pm.QuoteBypassQuoteCache(pool.Address, amountIn, tokenIn, tokenOut)
			}
			ts.Formula++

			if result.Eq(&evmResult) {
				ts.Match++
			} else {
				var diff uint256.Int
				isOver := result.Gt(&evmResult)
				if isOver {
					diff.Sub(&result, &evmResult)
				} else {
					diff.Sub(&evmResult, &result)
				}
				var scaled uint256.Int
				if pool.PoolType == 3 {
					scaled.Mul(&diff, uint256.NewInt(100_000))
				} else {
					scaled.Mul(&diff, uint256.NewInt(100_000_000))
				}
				denom := &evmResult
				if isOver {
					denom = &result
				}
				if !denom.IsZero() && scaled.Lt(denom) {
					ts.Match++ // within tolerance
				} else if isOver {
					ts.Overquote++
					mismatchSet[key] = true
					overquoteSet[key] = true
					tn := typeNames[pool.PoolType]
					if tn == "" {
						tn = fmt.Sprintf("type_%d", pool.PoolType)
					}
					mismatchLog = append(mismatchLog, fmt.Sprintf("  OVERQUOTE [%s] %s dir=%d formula=%s evm=%s (pool#%d)",
						tn, pool.Address.Hex(), ti, result.Dec(), evmResult.Dec(), i+2))
				} else {
					ts.Underquote++
					mismatchSet[key] = true
					if len(mismatchLog) < 200 {
						tn := typeNames[pool.PoolType]
						if tn == "" {
							tn = fmt.Sprintf("type_%d", pool.PoolType)
						}
						mismatchLog = append(mismatchLog, fmt.Sprintf("  UNDERQUOTE [%s] %s dir=%d formula=%s evm=%s (pool#%d)",
							tn, pool.Address.Hex(), ti, result.Dec(), evmResult.Dec(), i+2))
					}
				}
			}
			}
		}
	}

	// Distribute total wall time across types proportionally by formula count
	totalElapsedMs := float64(time.Since(t0).Nanoseconds()) / 1e6
	totalFormula := 0
	for _, ts := range byType {
		totalFormula += ts.Formula
	}
	if totalFormula > 0 {
		for _, ts := range byType {
			ts.HotMs = totalElapsedMs * float64(ts.Formula) / float64(totalFormula)
		}
	}

	return &blockResult{
		blockNum:     blockNum,
		byType:       byType,
		mismatchSet:  mismatchSet,
		overquoteSet: overquoteSet,
		mismatchLog:  mismatchLog,
	}, nil
}

// printTypeTable prints the per-type breakdown table to stderr and returns totals.
func printTypeTable(byType map[int]*typeStats, poolCount int) (totalQuotes, totalMatch, totalOver, totalUnder, totalNonZero, totalFmla int, totalHotMs float64) {
	fmt.Fprintf(os.Stderr, "\n%-16s %6s %8s %6s %8s %6s %6s %6s %9s\n",
		"TYPE", "POOLS", "QUOTES", "FMLA", "MS", "MATCH", "OVER!", "UNDER", "PRECISION")
	fmt.Fprintf(os.Stderr, "%s\n", strings.Repeat("-", 82))

	type sortEntry struct {
		poolType int
		ms       float64
	}
	var sorted []sortEntry
	for pt, s := range byType {
		sorted = append(sorted, sortEntry{pt, s.HotMs})
	}
	for i := 0; i < len(sorted); i++ {
		for j := i + 1; j < len(sorted); j++ {
			if sorted[j].ms > sorted[i].ms {
				sorted[i], sorted[j] = sorted[j], sorted[i]
			}
		}
	}

	for _, e := range sorted {
		s := byType[e.poolType]
		name := typeNames[e.poolType]
		if name == "" {
			name = fmt.Sprintf("type_%d", e.poolType)
		}
		pc := s.Quotes / 2
		total := s.Match + s.Overquote + s.Underquote
		precPct := 0.0
		if total > 0 {
			precPct = float64(s.Match) / float64(total) * 100
		}
		fmt.Fprintf(os.Stderr, "%-16s %6d %8d %6d %8.1f %6d %6d %6d %8.1f%%\n",
			name, pc, s.Quotes, s.Formula, s.HotMs, s.Match, s.Overquote, s.Underquote, precPct)
		totalQuotes += s.Quotes
		totalMatch += s.Match
		totalOver += s.Overquote
		totalUnder += s.Underquote
		totalNonZero += s.NonZero
		totalFmla += s.Formula
		totalHotMs += s.HotMs
	}

	fmt.Fprintf(os.Stderr, "%s\n", strings.Repeat("-", 82))
	totalTotal := totalMatch + totalOver + totalUnder
	totalPrecPct := 0.0
	if totalTotal > 0 {
		totalPrecPct = float64(totalMatch) / float64(totalTotal) * 100
	}
	fmt.Fprintf(os.Stderr, "%-16s %6d %8d %6d %8.1f %6d %6d %6d %8.1f%%\n",
		"TOTAL", poolCount, totalQuotes, totalFmla, totalHotMs, totalMatch, totalOver, totalUnder, totalPrecPct)
	return
}

// ─── Main ──────────────────────────────────────────────────────────

func main() {
	poolLimit := flag.Int("limit", 3500, "max pools to load")
	skipFormulas := flag.Bool("skip-formulas", false, "skip formula pass")
	numBlocksFlag := flag.Int("blocks", 10, "number of blocks to test")
	singlePoolFlag := flag.String("pool", "", "test a single pool address")
	stateServerFlag := flag.String("state-server", "ws://localhost:7449", "state server base URL")
	useCacheFlag := flag.Bool("cache", false, "use formula quote cache")
	cpuProfileFlag := flag.String("cpuprofile", "", "write CPU profile to file")
	memProfileFlag := flag.String("memprofile", "", "write memory profile to file")
	logResultFlag := flag.String("log", "", "append results to file")
	ecoFlag := flag.String("eco", "", "filter to a single ecosystem (e.g. pharaoh_v1)")
	flag.Parse()

	numBlocks := *numBlocksFlag
	singlePool := *singlePoolFlag
	stateServerHost := *stateServerFlag
	useCache := *useCacheFlag
	cpuProfile := *cpuProfileFlag
	memProfile := *memProfileFlag
	logResult := *logResultFlag
	_ = logResult
	if numBlocks < 1 {
		numBlocks = 1
	}

	// Compute block numbers
	blocks := make([]uint64, numBlocks)
	for i := 0; i < numBlocks; i++ {
		blocks[i] = uint64(router.DeployedBlock) + uint64(i)*10000
	}

	registry := formulas.LoadEmbeddedRegistry()
	pools := poolcollector.EmbeddedPools(*poolLimit)

	// Filter to single pool if --pool specified
	if singlePool != "" {
		target := common.HexToAddress(singlePool)
		var filtered []pathfinder.Pool
		for i := range pools {
			if pools[i].Address == target {
				filtered = append(filtered, pools[i])
				break
			}
		}
		if len(filtered) == 0 {
			fmt.Fprintf(os.Stderr, "pool %s not found in pool list\n", singlePool)
			os.Exit(1)
		}
		pools = filtered
	}

	// Filter to ecosystem if --eco specified
	if *ecoFlag != "" {
		ecoType := -1
		for pt, name := range typeNames {
			if name == *ecoFlag {
				ecoType = pt
				break
			}
		}
		if ecoType == -1 {
			fmt.Fprintf(os.Stderr, "unknown ecosystem %q, valid: ", *ecoFlag)
			for _, n := range typeNames {
				fmt.Fprintf(os.Stderr, "%s ", n)
			}
			fmt.Fprintln(os.Stderr)
			os.Exit(1)
		}
		var filtered []pathfinder.Pool
		for i := range pools {
			if pools[i].PoolType == ecoType {
				filtered = append(filtered, pools[i])
			}
		}
		fmt.Fprintf(os.Stderr, "[benchmark] eco filter %q: %d pools\n", *ecoFlag, len(filtered))
		pools = filtered
	}

	validated, invalid := registry.RegistryStats()
	fmt.Fprintf(os.Stderr, "[benchmark] registry: %d validated, %d invalid\n", validated, invalid)
	fmt.Fprintf(os.Stderr, "[benchmark] pools: %d, blocks: %d\n", len(pools), numBlocks)

	// Register V4 pools from ExtraData (block-independent)
	registerV4Pools(pools)

	// Build token overrides (block-independent)
	// Benchmark uses executeSwap (pool-level, no sender boundary fee) to validate formulas.
	// Router balance overrides only — no sender overrides needed.
	overrides := router.BuildTokenOverrides(ROUTER, pools)

	if cpuProfile != "" {
		f, _ := os.Create(cpuProfile)
		pprof.StartCPUProfile(f)
		defer pprof.StopCPUProfile()
	}
	if memProfile != "" {
		defer func() {
			f, _ := os.Create(memProfile)
			pprof.WriteHeapProfile(f)
			f.Close()
		}()
	}

	// Run benchmark for each block
	results := make([]*blockResult, 0, numBlocks)
	for idx, blockNum := range blocks {
		if numBlocks > 1 {
			fmt.Fprintf(os.Stderr, "\n=== Block %d (%d/%d) ===\n", blockNum, idx+1, numBlocks)
		}

		res, err := runBlockBenchmark(blockNum, registry, pools, overrides, *skipFormulas, stateServerHost, useCache)
		if err != nil {
			fmt.Fprintf(os.Stderr, "ERROR: %v\n", err)
			os.Exit(1)
		}
		results = append(results, res)

		// Print mismatches for this block
		for _, line := range res.mismatchLog {
			fmt.Fprintln(os.Stderr, line)
		}

		// Print per-type breakdown for this block
		_, totalMatch, totalOver, totalUnder, _, _, _ := printTypeTable(res.byType, len(pools))
		totalAll := totalMatch + totalOver + totalUnder
		precPct := 0.0
		if totalAll > 0 {
			precPct = float64(totalMatch) / float64(totalAll) * 100
		}
		if totalOver > 0 {
			fmt.Fprintf(os.Stderr, "\n!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n")
			fmt.Fprintf(os.Stderr, "!!! OVERQUOTING: %d quotes have formula > EVM              !!!\n", totalOver)
			fmt.Fprintf(os.Stderr, "!!! This is NEVER acceptable. Fix formula or set pool -1   !!!\n")
			fmt.Fprintf(os.Stderr, "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n")
		}
		fmt.Fprintf(os.Stderr, "\n[result] block %d: overquoting=%d, precision=%.1f%% (%d match, %d under)\n",
			blockNum, totalOver, precPct, totalMatch, totalUnder)
	}

	// ─── Cross-block aggregation (only when N > 1) ───
	if numBlocks > 1 {
		fmt.Fprintf(os.Stderr, "\n=== AGGREGATE (%d blocks) ===\n", numBlocks)

		// A pool+direction is "correct" only if it matched EVM on ALL blocks
		aggByType := make(map[int]*typeStats)
		aggGetStats := func(poolType int) *typeStats {
			if s, ok := aggByType[poolType]; ok {
				return s
			}
			s := &typeStats{}
			aggByType[poolType] = s
			return s
		}

		// Use first block's structure as template for iteration
		first := results[0]
		for i := range pools {
			pool := &pools[i]
			for ti := range pool.Tokens {
				for tj := range pool.Tokens {
					if ti == tj {
						continue
					}
					key := quoteKey{pool.Address, ti, tj}
					ts := aggGetStats(pool.PoolType)
					ts.Quotes++

					// Check across all blocks
					anyOver := false
					anyMismatch := false
					for _, res := range results {
						if res.overquoteSet[key] {
							anyOver = true
						}
						if res.mismatchSet[key] {
							anyMismatch = true
						}
					}
					if anyOver {
						ts.Overquote++
					} else if anyMismatch {
						ts.Underquote++
					} else {
						ts.Match++
					}
				}
			}
		}

		// Aggregate NonZero, Formula, HotMs from first block's byType
		for pt, fs := range first.byType {
			ts := aggGetStats(pt)
			ts.NonZero = fs.NonZero
			ts.Formula = fs.Formula
			ts.HotMs = fs.HotMs
		}

		_, totalMatch, totalOver, totalUnder, _, _, _ := printTypeTable(aggByType, len(pools))
		totalAll := totalMatch + totalOver + totalUnder
		precPct := 0.0
		if totalAll > 0 {
			precPct = float64(totalMatch) / float64(totalAll) * 100
		}
		if totalOver > 0 {
			fmt.Fprintf(os.Stderr, "\n!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n")
			fmt.Fprintf(os.Stderr, "!!! OVERQUOTING: %d quotes have formula > EVM              !!!\n", totalOver)
			fmt.Fprintf(os.Stderr, "!!! This is NEVER acceptable. Fix formula or set pool -1   !!!\n")
			fmt.Fprintf(os.Stderr, "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n")
		}
		fmt.Fprintf(os.Stderr, "\n[result] AGGREGATE: overquoting=%d, precision=%.1f%% (%d match, %d under)\n",
			totalOver, precPct, totalMatch, totalUnder)
	}

	// ─── Log output ───
	first := results[0]
	firstMatch, firstOver, firstUnder, firstFmla := 0, 0, 0, 0
	firstHotMs := 0.0
	for _, s := range first.byType {
		firstMatch += s.Match
		firstOver += s.Overquote
		firstUnder += s.Underquote
		firstFmla += s.Formula
		firstHotMs += s.HotMs
	}
	firstAll := firstMatch + firstOver + firstUnder
	firstPrecPct := 0.0
	if firstAll > 0 {
		firstPrecPct = float64(firstMatch) / float64(firstAll) * 100
	}
	msPerPool := firstHotMs / float64(len(pools))

	// Append to results.log
	if logResult == "" && !*skipFormulas {
		logResult = "benchmarks/formula-accuracy/results.log"
	}
	if logResult != "" {
		gitHash := "unknown"
		if gitOut, gitErr := exec.Command("git", "rev-parse", "--short", "HEAD").Output(); gitErr == nil {
			gitHash = strings.TrimSpace(string(gitOut))
		}
		logTs := time.Now().Format("2006-01-02_15:04")
		line := fmt.Sprintf("time=%s git=%s blocks=%d ms_per_pool=%.4f total_ms=%.1f pools=%d formula=%d match=%d overquote=%d underquote=%d precision=%.1f\n",
			logTs, gitHash, numBlocks, msPerPool, firstHotMs, len(pools), firstFmla, firstMatch, firstOver, firstUnder, firstPrecPct)
		logF, logErr := os.OpenFile(logResult, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
		if logErr == nil {
			logF.WriteString(line)
			logF.Close()
			fmt.Fprintf(os.Stderr, "\nLogged to %s\n", logResult)
		}
	}
}

// registerV4Pools parses V4 pool ExtraData and registers them with the formula system.
func registerV4Pools(pools []pathfinder.Pool) {
	count := 0
	for _, p := range pools {
		if p.PoolType != 9 || p.ExtraData == "" {
			continue
		}
		// ExtraData format: id=0x...,fee=18,ts=1,hooks=0x...
		var poolIdHex string
		var fee uint32
		var tickSpacing int32
		var hooks string
		for _, kv := range strings.Split(p.ExtraData, ",") {
			parts := strings.SplitN(kv, "=", 2)
			if len(parts) != 2 {
				continue
			}
			switch parts[0] {
			case "id":
				poolIdHex = parts[1]
			case "fee":
				var f int
				fmt.Sscanf(parts[1], "%d", &f)
				fee = uint32(f)
			case "ts":
				var t int
				fmt.Sscanf(parts[1], "%d", &t)
				tickSpacing = int32(t)
			case "hooks":
				hooks = parts[1]
			}
		}
		if poolIdHex == "" || tickSpacing == 0 {
			continue
		}
		var poolId [32]byte
		idBytes := common.FromHex(poolIdHex)
		copy(poolId[:], idBytes)

		var hookFeePpm uint32
		var hooksAddr common.Address
		if hooks != "" {
			hooksAddr = common.HexToAddress(hooks)
		}

		poolAddr := strings.ToLower(p.Address.Hex())
		formulas.RegisterV4Pool(poolAddr, poolId, tickSpacing, fee, hookFeePpm, hooksAddr)
		count++
	}
	if count > 0 {
		fmt.Fprintf(os.Stderr, "[benchmark] registered %d V4 pools\n", count)
	}
}

// balV3VaultAddr is the Balancer V3 vault on Avalanche C-Chain.
var balV3VaultAddr = common.HexToAddress("0xba1333333333a1ba1108e8412f11850a5c319ba9")

// balV3ReadTokenInfo reads TokenInfo for a token from vault storage.
// TokenInfo is packed as: byte0=tokenType, bytes1-20=rateProvider, byte21=paysYieldFees.
// Stored in _poolTokenInfo[pool][token] at vault slot 4.
func balV3ReadTokenInfo(state *statedb.StateDB, pool, token common.Address) (tokenType uint8, rateProvider common.Address) {
	// outer slot: keccak256(pool ++ 4)
	outerKey := make([]byte, 64)
	copy(outerKey[12:32], pool.Bytes())
	outerKey[63] = 4
	outerSlot := crypto.Keccak256Hash(outerKey)

	// inner slot: keccak256(token ++ outerSlot)
	innerKey := make([]byte, 64)
	copy(innerKey[12:32], token.Bytes())
	copy(innerKey[32:64], outerSlot.Bytes())
	innerSlot := crypto.Keccak256Hash(innerKey)

	packed := state.GetState(balV3VaultAddr, innerSlot)
	val := new(big.Int).SetBytes(packed[:])

	// byte 0 (LSB): tokenType
	tokenType = uint8(val.Uint64() & 0xff)
	// bytes 1-20: rateProvider address
	rpInt := new(big.Int).And(new(big.Int).Rsh(val, 8), new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), 160), big.NewInt(1)))
	rateProvider = common.BigToAddress(rpInt)
	return
}

// registerBalancerV3Pools discovers and registers Balancer V3 pool parameters via EVM calls.
func registerBalancerV3Pools(pools []pathfinder.Pool, state *statedb.StateDB, cfg statedb.EVMConfig, registry *formulas.Registry) {
	count := 0
	for _, p := range pools {
		if p.PoolType != 6 || len(p.Tokens) < 2 {
			continue
		}
		poolAddr := strings.ToLower(p.Address.Hex())

		// Read per-token types and rate providers from vault storage.
		tokenTypes := make([]formulas.BalV3TokenType, len(p.Tokens))
		rateProviders := make([]common.Address, len(p.Tokens))
		for i, tok := range p.Tokens {
			tt, rp := balV3ReadTokenInfo(state, p.Address, tok)
			tokenTypes[i] = formulas.BalV3TokenType(tt)
			rateProviders[i] = rp
		}

		// Try getAmplificationParameter() → selector 0x6daccffa
		ampSelector := common.FromHex("0x6daccffa")
		ampResult, _, err := statedb.ExecuteCall(state, cfg, DUMMY_SENDER, p.Address, ampSelector)
		if err == nil && len(ampResult) >= 96 {
			ampVal := new(big.Int).SetBytes(ampResult[0:32])
			if ampVal.Sign() > 0 {
				info := &formulas.BalancerV3PoolInfo{
					PoolType:      formulas.BalV3Stable,
					NumTokens:     len(p.Tokens),
					Tokens:        p.Tokens,
					Amp:           ampVal,
					TokenTypes:    tokenTypes,
					RateProviders: rateProviders,
				}
				formulas.RegisterBalancerV3Pool(poolAddr, info)
				registry.SetFormulaID(p.Address, formulas.FormulaBalancerV3)
				count++
				continue
			}
		}

		// Try getNormalizedWeights() → selector 0xf89f27ed
		weightsSelector := common.FromHex("0xf89f27ed")
		weightsResult, _, err := statedb.ExecuteCall(state, cfg, DUMMY_SENDER, p.Address, weightsSelector)
		if err == nil && len(weightsResult) >= 96 {
			if len(weightsResult) >= 64 {
				numWeights := new(big.Int).SetBytes(weightsResult[32:64]).Int64()
				if numWeights == int64(len(p.Tokens)) && len(weightsResult) >= 64+int(numWeights)*32 {
					weights := make([]*big.Int, numWeights)
					allValid := true
					for i := int64(0); i < numWeights; i++ {
						off := 64 + i*32
						weights[i] = new(big.Int).SetBytes(weightsResult[off : off+32])
						if weights[i].Sign() <= 0 {
							allValid = false
							break
						}
					}
					if allValid {
						info := &formulas.BalancerV3PoolInfo{
							PoolType:      formulas.BalV3Weighted,
							NumTokens:     len(p.Tokens),
							Tokens:        p.Tokens,
							Weights:       weights,
							TokenTypes:    tokenTypes,
							RateProviders: rateProviders,
						}
						formulas.RegisterBalancerV3Pool(poolAddr, info)
						registry.SetFormulaID(p.Address, formulas.FormulaBalancerV3)
						count++
						continue
					}
				}
			}
		}

		// Pool type 6 but neither Stable nor Weighted (e.g. GyroECLP).
		// Register FormulaBalancerV3 without a pool info entry so that
		// newBalancerV3Pool returns nil, and PoolManager.Get() caches a
		// deadPoolQuoter — preventing EVM fallback entirely.
		registry.SetFormulaID(p.Address, formulas.FormulaBalancerV3)
	}
	if count > 0 {
		fmt.Fprintf(os.Stderr, "[benchmark] registered %d Balancer V3 pools\n", count)
	}
}

// registerBalancerV2Pools discovers and registers Balancer V2 weighted pool parameters via EVM calls.
// It uses getNormalizedWeights() and getSwapFeePercentage() on each pool contract.
// Balances are read from Vault storage at quote time (not cached here).
func registerBalancerV2Pools(pools []pathfinder.Pool, state *statedb.StateDB, cfg statedb.EVMConfig, registry *formulas.Registry) {
	count := 0
	for _, p := range pools {
		if p.PoolType != 16 || len(p.Tokens) < 2 {
			continue
		}
		// Parse poolId from ExtraData (@poolId=0x...)
		var poolIdHex string
		for _, kv := range strings.Split(p.ExtraData, ",") {
			parts := strings.SplitN(kv, "=", 2)
			if len(parts) == 2 && parts[0] == "poolId" {
				poolIdHex = parts[1]
			}
		}
		if poolIdHex == "" {
			continue
		}
		poolIdBytes := common.FromHex(poolIdHex)
		if len(poolIdBytes) != 32 {
			continue
		}
		var poolId [32]byte
		copy(poolId[:], poolIdBytes)

		poolAddr := strings.ToLower(p.Address.Hex())
		numTokens := len(p.Tokens)

		// Determine specialization from poolId bytes 20-21 (big-endian).
		spec := (int(poolId[20]) << 8) | int(poolId[21])
		if spec != 0 && spec != 1 && spec != 2 {
			// General (0), MinimalSwapInfo (1), and TwoToken (2) supported.
			continue
		}

		// Fetch normalized weights: getNormalizedWeights() selector = 0xf89f27ed
		weightsSelector := common.FromHex("0xf89f27ed")
		weightsResult, _, err := statedb.ExecuteCall(state, cfg, DUMMY_SENDER, p.Address, weightsSelector)
		if err != nil || len(weightsResult) < 96 {
			continue
		}
		// ABI decode: uint256[] — offset(32) + length(32) + data(32*n)
		numWeights := new(big.Int).SetBytes(weightsResult[32:64]).Int64()
		if numWeights != int64(numTokens) || len(weightsResult) < 64+int(numWeights)*32 {
			continue
		}
		weights := make([]*big.Int, numWeights)
		allValid := true
		for i := int64(0); i < numWeights; i++ {
			off := 64 + i*32
			weights[i] = new(big.Int).SetBytes(weightsResult[off : off+32])
			if weights[i].Sign() <= 0 {
				allValid = false
				break
			}
		}
		if !allValid {
			continue
		}

		// Fetch swap fee: getSwapFeePercentage() selector = 0x55c67628
		feeSelector := common.FromHex("0x55c67628")
		feeResult, _, err := statedb.ExecuteCall(state, cfg, DUMMY_SENDER, p.Address, feeSelector)
		if err != nil || len(feeResult) < 32 {
			continue
		}
		swapFee := new(big.Int).SetBytes(feeResult[0:32])
		if swapFee.Sign() <= 0 {
			continue
		}

		// Build per-token scaling factors from token decimal counts.
		// scalingFactor = 10^(18 - decimals).  We fetch decimals() from each token.
		scalingFactors := make([]*big.Int, numTokens)
		decimalsSelector := common.FromHex("0x313ce567") // decimals()
		sfValid := true
		for i, tok := range p.Tokens {
			decResult, _, err := statedb.ExecuteCall(state, cfg, DUMMY_SENDER, tok, decimalsSelector)
			if err != nil || len(decResult) < 32 {
				sfValid = false
				break
			}
			dec := new(big.Int).SetBytes(decResult[24:32]).Int64() // last byte is sufficient
			if dec < 0 || dec > 18 {
				sfValid = false
				break
			}
			exp := int64(18) - dec
			scalingFactors[i] = new(big.Int).Exp(big.NewInt(10), big.NewInt(exp), nil)
		}
		if !sfValid {
			continue
		}

		info := &formulas.BalancerV2PoolInfo{
			PoolId:            poolId,
			Specialization:    spec,
			NumTokens:         numTokens,
			Tokens:            p.Tokens,
			Weights:           weights,
			SwapFeePercentage: swapFee,
			ScalingFactors:    scalingFactors,
		}
		formulas.RegisterBalancerV2Pool(poolAddr, info)
		registry.SetFormulaID(p.Address, formulas.FormulaBalancerV2)
		count++
	}
	if count > 0 {
		fmt.Fprintf(os.Stderr, "[benchmark] registered %d Balancer V2 pools\n", count)
	}
}
